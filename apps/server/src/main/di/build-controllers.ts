import type { FastifyController } from '../../api/contracts/fastify-controller';
import {
  ActiveChurchController,
  AssignController,
  CallerCapabilitiesController,
  ChurchSettingsController,
  CycleAdminController,
  EventController,
  EventTemplateAdminController,
  EventTimeBlockAdminController,
  InvitationController,
  MinistryAdminController,
  MinistryController,
  MinistryRoleController,
  NotificationController,
  PeopleController,
  PlanningEventAdminController,
  PrepareController,
  PublicChurchProfileController,
  RedemptionController,
  SectorController,
  SwapRequestController,
  SwapRequestListController,
  UsualSetupController,
  VolunteerController,
  VolunteerScheduleController,
} from '../../api/controllers';
import type { BuildControllersInput } from './build-controllers.types';

export function buildControllers({
  config,
  managers: {
    assignmentManager,
    eventManager,
    eventTemplateManager,
    ministryManager,
    ministryInvitationManager,
    ministryRoleManager,
    sectorManager,
    redemptionManager,
    volunteerTransferManager,
    cycleManager,
    planningEventManager,
    volunteerManager,
    swapRequestManager,
    swapRequestListManager,
    prepareManager,
    usualSetupManager,
    scheduleBuilderReader,
    assignmentProposalManager,
    scheduleReadModel,
    schedulePublisher,
    availabilityCheckManager,
    activeChurchSelectionManager,
    notificationManager,
    invitationListManager,
    peopleListManager,
    setupProgressManager,
    churchSettingsManager,
    publicChurchProfileManager,
    publicEventManager,
    churchAccessManager,
    ministryMembershipManager,
  },
  services: { webShell, sessionGateway },
  auth: { authorityGuard, activeChurchResolver },
}: BuildControllersInput): FastifyController[] {
  return [
    new ActiveChurchController({
      activeChurchResolver,
      sessionGateway,
      selectionManager: activeChurchSelectionManager,
    }),
    new CycleAdminController({
      cycleManager,
      setupProgressManager,
      activeChurchResolver,
      sessionGateway,
      authorityGuard,
    }),
    new EventTemplateAdminController({
      eventTemplateManager,
      activeChurchResolver,
      sessionGateway,
      authorityGuard,
    }),
    new PlanningEventAdminController({
      planningEventManager,
      activeChurchResolver,
      sessionGateway,
      authorityGuard,
    }),
    new EventTimeBlockAdminController({
      planningEventManager,
      activeChurchResolver,
      sessionGateway,
      authorityGuard,
    }),
    new MinistryAdminController({
      ministryManager,
      activeChurchResolver,
      sessionGateway,
      authorityGuard,
    }),
    new ChurchSettingsController({
      churchSettingsManager,
      activeChurchResolver,
      sessionGateway,
      authorityGuard,
    }),
    new EventController({
      eventManager,
      activeChurchResolver,
      sessionGateway,
      authorityGuard,
    }),
    new MinistryController({
      ministryManager,
      ministryInvitationManager,
      activeChurchResolver,
      sessionGateway,
      authorityGuard,
      config,
    }),
    new MinistryRoleController({
      ministryRoleManager,
      activeChurchResolver,
      sessionGateway,
      authorityGuard,
    }),
    new SectorController({
      ministryManager,
      sectorManager,
      activeChurchResolver,
      sessionGateway,
      authorityGuard,
    }),
    new UsualSetupController({
      ministryManager,
      usualSetupManager,
      activeChurchResolver,
      sessionGateway,
      authorityGuard,
    }),
    new PrepareController({
      prepareManager,
      scheduleReadModel,
      availabilityCheckManager,
      activeChurchResolver,
      sessionGateway,
      authorityGuard,
      config,
    }),
    new AssignController({
      scheduleBuilderReader,
      assignmentProposalManager,
      schedulePublisher,
      scheduleReadModel,
      assignmentManager,
      activeChurchResolver,
      sessionGateway,
      authorityGuard,
      config,
    }),
    new CallerCapabilitiesController({
      activeChurchResolver,
      sessionGateway,
      authorityGuard,
    }),
    new NotificationController({
      notificationManager,
      activeChurchResolver,
      sessionGateway,
      authorityGuard,
      maxPageSize: config.notifications.maxPageSize,
    }),
    new InvitationController({
      invitationListManager,
      ministryInvitationManager,
      activeChurchResolver,
      sessionGateway,
      authorityGuard,
      maxPageSize: config.invitations.maxPageSize,
    }),
    new PeopleController({
      peopleListManager,
      churchAccessManager,
      ministryMembershipManager,
      activeChurchResolver,
      sessionGateway,
      authorityGuard,
      config,
    }),
    new RedemptionController({
      redemptionManager,
      volunteerTransferManager,
      sessionGateway,
      config,
    }),
    new PublicChurchProfileController({
      publicChurchProfileManager,
      publicEventManager,
      webShell,
      config,
    }),
    new VolunteerController({
      volunteerManager,
      activeChurchResolver,
      sessionGateway,
    }),
    new VolunteerScheduleController({
      volunteerManager,
      activeChurchResolver,
      sessionGateway,
    }),
    new SwapRequestController({
      swapRequestManager,
      activeChurchResolver,
      sessionGateway,
    }),
    new SwapRequestListController({
      swapRequestListManager,
      swapRequestManager,
      activeChurchResolver,
      sessionGateway,
      authorityGuard,
    }),
  ];
}
