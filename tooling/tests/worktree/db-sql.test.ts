import { execFileSync, spawnSync } from 'node:child_process';
import {
  chmodSync,
  existsSync,
  mkdtempSync,
  readFileSync,
  realpathSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'bun:test';

/**
 * Drives the real `db:sql` script from a linked worktree, with `docker`, `sg`
 * and `id` replaced on PATH.
 */

const REPO_ROOT = resolve(import.meta.dir, '../../..');
const DB_SQL = resolve(REPO_ROOT, 'tooling/worktree/db-sql.ts');
const GENERATED_HEADER =
  '# Generated by `bun run env:local` (tooling/worktree/local-env.ts). Do not edit; rerun it.';

let sandbox: string;
let bin: string;
let primary: string;
let feature: string;
let dockerLog: string;
let sgLog: string;

interface FakeInput {
  name: string;
  script: string;
}

function fake(input: FakeInput): void {
  const path = join(bin, input.name);
  writeFileSync(path, `#!/bin/sh\n${input.script}\n`);
  chmodSync(path, 0o755);
}

interface GroupsInput {
  session: string;
  account: string;
}

/** `id -nG` is the shell's groups; `id -nG <user>` is the account's. */
function fakeGroups({ session, account }: GroupsInput): void {
  fake({
    name: 'id',
    script: `if [ "$#" -gt 1 ]; then echo "${account}"; else echo "${session}"; fi`,
  });
}

interface RunInput {
  args: string[];
}

function run({ args }: RunInput) {
  return spawnSync(process.execPath, [DB_SQL, ...args], {
    cwd: feature,
    encoding: 'utf8',
    env: { HOME: sandbox, PATH: bin },
  });
}

/** One line per argument docker received. */
function dockerArguments(): string[] {
  return readFileSync(dockerLog, 'utf8').trimEnd().split('\n');
}

function expectedArguments(psqlArguments: string[]): string[] {
  return [
    'compose',
    '--file',
    `${primary}/docker-compose.yml`,
    'exec',
    '-T',
    'db',
    'psql',
    '-U',
    'postgres',
    '-d',
    'church_feature__0000_dev',
    ...psqlArguments,
  ];
}

beforeEach(() => {
  sandbox = realpathSync(mkdtempSync(join(tmpdir(), 'church-db-sql-')));
  bin = join(sandbox, 'bin');
  primary = join(sandbox, 'church');
  feature = join(sandbox, 'church.feature');
  dockerLog = join(sandbox, 'docker.log');
  sgLog = join(sandbox, 'sg.log');
  execFileSync('mkdir', [bin]);
  for (const tool of ['sh', 'git', 'dirname']) {
    symlinkSync(Bun.which(tool) as string, join(bin, tool));
  }
  fake({ name: 'docker', script: `printf '%s\\n' "$@" > "${dockerLog}"` });
  fake({ name: 'sg', script: `echo "$1" > "${sgLog}"\nexec sh -c "$3"` });
  fakeGroups({ session: 'me docker', account: 'me docker' });

  execFileSync('git', ['init', '-q', '-b', 'develop', primary]);
  execFileSync(
    'git',
    [
      '-c',
      'user.name=test',
      '-c',
      'user.email=test@example.com',
      'commit',
      '-q',
      '--allow-empty',
      '-m',
      'init',
    ],
    { cwd: primary },
  );
  execFileSync('git', ['worktree', 'add', '-q', '-b', 'feature', feature], {
    cwd: primary,
  });
  writeFileSync(
    join(feature, '.env.local'),
    `${GENERATED_HEADER}\nCHURCH_WORKTREE=feature__0000\n`,
  );
});

afterEach(() => {
  rmSync(sandbox, { recursive: true, force: true });
});

describe('db:sql', () => {
  it("runs psql in the shared db service on this worktree's development database", () => {
    const result = run({ args: ['-c', 'select 1'] });

    expect(result.status, result.stderr).toBe(0);
    expect(dockerArguments()).toEqual(expectedArguments(['-c', 'select 1']));
    expect(existsSync(sgLog)).toBe(false);
  });

  it('drops a leading `--` that the script runner passes through', () => {
    const result = run({ args: ['--', '-c', 'select 1'] });

    expect(result.status, result.stderr).toBe(0);
    expect(dockerArguments()).toEqual(expectedArguments(['-c', 'select 1']));
  });

  it('goes through `sg docker` when the shell has not picked up the group, keeping each argument', () => {
    fakeGroups({ session: 'me', account: 'me docker' });
    const query = `select 'it''s', "name" from "user" where id = $1; -- $(false)`;

    const result = run({ args: ['-c', query] });

    expect(result.status, result.stderr).toBe(0);
    expect(readFileSync(sgLog, 'utf8').trim()).toBe('docker');
    expect(dockerArguments()).toEqual(expectedArguments(['-c', query]));
  });

  it("exits with psql's status", () => {
    fake({ name: 'docker', script: 'exit 3' });

    expect(run({ args: ['-c', 'nope'] }).status).toBe(3);
  });

  it('says that it needs Docker on a machine without it', () => {
    rmSync(join(bin, 'docker'));

    const result = run({ args: ['-c', 'select 1'] });

    expect(result.status).toBe(1);
    expect(result.stderr).toContain(
      '✖ db:sql needs Docker: there is no `docker` command on this machine.',
    );
  });

  it('refuses a worktree without a generated identity', () => {
    rmSync(join(feature, '.env.local'));

    const result = run({ args: ['-c', 'select 1'] });

    expect(result.status).toBe(1);
    expect(result.stderr).toContain(
      '✖ db:sql: this worktree has no generated .env.local identity. Run `bun run env:local` first.',
    );
    expect(existsSync(dockerLog)).toBe(false);
  });
});
