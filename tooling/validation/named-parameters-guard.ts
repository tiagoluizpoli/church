import { dirname, relative, resolve } from 'node:path';
import ts from 'typescript';
import { readApplicationSourceFiles, type SourceFile } from './source-files';

const REPO_ROOT = resolve(import.meta.dir, '../..');
const CHECKED_PATH_PATTERN = /^(?:apps|packages)\/[^/]+\/src\//;
const SKIPPED_PATH_PATTERN =
  /\/tests\/|\/paraglide\/|\.gen\.[cm]?[jt]sx?$|\.d\.[cm]?ts$/;
const PARAMETER_FIX = 'take one object parameter with a named type';

const PARAMETER_KINDS = new Map<ts.SyntaxKind, string>([
  [ts.SyntaxKind.FunctionDeclaration, 'function'],
  [ts.SyntaxKind.FunctionExpression, 'function expression'],
  [ts.SyntaxKind.ArrowFunction, 'arrow function'],
  [ts.SyntaxKind.MethodDeclaration, 'method'],
  [ts.SyntaxKind.Constructor, 'constructor'],
  [ts.SyntaxKind.MethodSignature, 'method signature'],
  [ts.SyntaxKind.CallSignature, 'call signature'],
  [ts.SyntaxKind.ConstructSignature, 'construct signature'],
  [ts.SyntaxKind.FunctionType, 'function type'],
  [ts.SyntaxKind.ConstructorType, 'constructor type'],
]);

const COMPILER_OPTIONS: ts.CompilerOptions = {
  allowJs: true,
  jsx: ts.JsxEmit.ReactJSX,
  module: ts.ModuleKind.ESNext,
  moduleResolution: ts.ModuleResolutionKind.Bundler,
  noEmit: true,
  skipLibCheck: true,
  target: ts.ScriptTarget.ESNext,
};

const INLINE_TYPE_FIX = 'declare it as a named interface or type';
const SUPPRESSION_PATTERN = /^\s*\/\/\s*named-parameters-ignore\b:?(.*)$/;

const GENERATED_HEADER_PATTERN =
  /^\s*\/\*[\s\S]*?(?:Generated by|Do not edit manually)[\s\S]*?\*\//;

const isChecked = ({ path, source }: SourceFile) =>
  CHECKED_PATH_PATTERN.test(path) &&
  !SKIPPED_PATH_PATTERN.test(path) &&
  !GENERATED_HEADER_PATTERN.test(source);

interface ProjectResolution {
  options: ts.CompilerOptions;
  cache: ts.ModuleResolutionCache;
}

const projectResolutions = new Map<string, ProjectResolution>();

// Each project resolves its own path aliases (`@/…`), so module resolution
// uses the options of the tsconfig.json beside the importing file's project.
function resolutionFor(fileName: string): ProjectResolution {
  const project =
    relative(REPO_ROOT, fileName).match(/^(?:apps|packages)\/[^/]+/)?.[0] ?? '';
  const cached = projectResolutions.get(project);
  if (cached) return cached;
  const { config } = ts.readConfigFile(
    resolve(REPO_ROOT, project, 'tsconfig.json'),
    ts.sys.readFile,
  );
  const options =
    project && config
      ? ts.parseJsonConfigFileContent(
          config,
          { ...ts.sys, readDirectory: () => [] },
          resolve(REPO_ROOT, project),
        ).options
      : COMPILER_OPTIONS;
  const resolution = {
    options,
    cache: ts.createModuleResolutionCache(REPO_ROOT, (name) => name, options),
  };
  projectResolutions.set(project, resolution);
  return resolution;
}

function createProgram({ files }: { files: SourceFile[] }): ts.Program {
  const sources = new Map(
    files.map(({ path, source }) => [resolve(REPO_ROOT, path), source]),
  );
  const host = ts.createCompilerHost(COMPILER_OPTIONS, true);
  const readSourceFile = host.getSourceFile;
  host.getSourceFile = (fileName, languageVersion, ...rest) => {
    const source = sources.get(fileName);
    return source === undefined
      ? readSourceFile(fileName, languageVersion, ...rest)
      : ts.createSourceFile(fileName, source, languageVersion, true);
  };
  host.fileExists = (fileName) =>
    sources.has(fileName) || ts.sys.fileExists(fileName);
  host.readFile = (fileName) =>
    sources.get(fileName) ?? ts.sys.readFile(fileName);
  const directories = new Set<string>();
  for (const fileName of sources.keys()) {
    for (
      let d = dirname(fileName);
      !directories.has(d) && d !== '/';
      d = dirname(d)
    ) {
      directories.add(d);
    }
  }
  host.directoryExists = (directory) =>
    directories.has(directory) || ts.sys.directoryExists(directory);
  host.resolveModuleNameLiterals = (literals, containingFile) =>
    literals.map((literal) => {
      const { options, cache } = resolutionFor(containingFile);
      return ts.resolveModuleName(
        literal.text,
        containingFile,
        options,
        host,
        cache,
      );
    });
  return ts.createProgram([...sources.keys()], COMPILER_OPTIONS, host);
}

function countParameters(node: ts.SignatureDeclaration): number {
  const [first] = node.parameters;
  const hasThis =
    first && ts.isIdentifier(first.name) && first.name.text === 'this';
  return node.parameters.length - (hasThis ? 1 : 0);
}

// The position an inline object type is written in, or undefined when it
// sits in a named type (alias, interface member).
function inlineTypePosition(node: ts.TypeLiteralNode): string | undefined {
  let child: ts.Node = node;
  let owner = node.parent;
  while (ts.isTypeNode(owner)) {
    child = owner;
    owner = owner.parent;
  }
  if (ts.isParameter(owner)) return 'parameter';
  if (ts.isVariableDeclaration(owner)) return 'variable';
  if (ts.isAsExpression(owner) || ts.isTypeAssertionExpression(owner)) {
    return '"as" cast';
  }
  if (ts.isFunctionLike(owner) && owner.type === child) return 'return type';
  return undefined;
}

// The call a function is written directly into, as an argument or as an
// object property value of an argument.
function enclosingCall(node: ts.Node): ts.CallLikeExpression | undefined {
  let argument = node;
  if (
    ts.isMethodDeclaration(node) &&
    ts.isObjectLiteralExpression(node.parent)
  ) {
    argument = node.parent;
  }
  while (
    ts.isPropertyAssignment(argument.parent) &&
    ts.isObjectLiteralExpression(argument.parent.parent)
  ) {
    argument = argument.parent.parent;
  }
  const call = argument.parent;
  return (ts.isCallExpression(call) || ts.isNewExpression(call)) &&
    call.arguments?.includes(argument as ts.Expression)
    ? call
    : undefined;
}

function isDependencyCallback({
  node,
  program,
}: {
  node: ts.Node;
  program: ts.Program;
}): boolean {
  const call = enclosingCall(node);
  const declaration =
    call && program.getTypeChecker().getResolvedSignature(call)?.declaration;
  if (!declaration) return false;
  const sourceFile = declaration.getSourceFile();
  return (
    sourceFile.fileName.includes('/node_modules/') ||
    program.isSourceFileDefaultLibrary(sourceFile)
  );
}

// The statement or member a failing node belongs to: what a suppression
// comment sits directly above.
function declarationOf(node: ts.Node): ts.Node {
  let declaration = node;
  while (
    !ts.isSourceFile(declaration.parent) &&
    !ts.isStatement(declaration) &&
    !ts.isClassElement(declaration) &&
    !ts.isTypeElement(declaration) &&
    !ts.isObjectLiteralElementLike(declaration)
  ) {
    declaration = declaration.parent;
  }
  return declaration;
}

export function getNamedParameterFailures({
  files,
}: {
  files: SourceFile[];
}): string[] {
  const checkedFiles = files.filter(isChecked);
  if (checkedFiles.length === 0) return [];
  const program = createProgram({ files });
  return checkedFiles.flatMap(({ path }) => {
    const sourceFile = program.getSourceFile(resolve(REPO_ROOT, path));
    if (!sourceFile) return [];
    const failures: string[] = [];
    const lineOf = (node: ts.Node) =>
      sourceFile.getLineAndCharacterOfPosition(node.getStart()).line + 1;
    const suppressedLines = new Set<number>();
    sourceFile.text.split('\n').forEach((text, index) => {
      const suppression = text.match(SUPPRESSION_PATTERN);
      if (!suppression) return;
      suppressedLines.add(index + 2);
      if (!suppression[1]?.trim()) {
        failures.push(
          `${path}:${index + 1}: named-parameters-ignore needs a reason: // named-parameters-ignore: <why the signature is not ours>`,
        );
      }
    });
    const report = ({ node, message }: { node: ts.Node; message: string }) => {
      if (!suppressedLines.has(lineOf(declarationOf(node)))) {
        failures.push(`${path}:${lineOf(node)}: ${message}`);
      }
    };

    const visit = (node: ts.Node) => {
      const kind = PARAMETER_KINDS.get(node.kind);
      if (kind) {
        const count = countParameters(node as ts.SignatureDeclaration);
        if (count > 1 && !isDependencyCallback({ node, program })) {
          report({
            node,
            message: `${kind} takes ${count} parameters: ${PARAMETER_FIX}`,
          });
        }
      }
      const position = ts.isTypeLiteralNode(node)
        ? inlineTypePosition(node)
        : undefined;
      if (position) {
        report({
          node,
          message: `inline object type in a ${position}: ${INLINE_TYPE_FIX}`,
        });
      }
      ts.forEachChild(node, visit);
    };
    visit(sourceFile);
    return failures;
  });
}

if (import.meta.main) {
  const failures = getNamedParameterFailures({
    files: readApplicationSourceFiles().filter(isChecked),
  });

  if (failures.length > 0) {
    console.error(failures.join('\n'));
    process.exitCode = 1;
  }
}
