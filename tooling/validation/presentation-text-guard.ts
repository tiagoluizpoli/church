import { readFileSync } from 'node:fs';
import ts from 'typescript';
import { readApplicationSourceFiles, type SourceFile } from './source-files';

const FIX = 'use a catalog message (m.*) or pass translated content';
const LETTER = /\p{L}/u;
// Technical content that may sit inside presentation text without being copy.
const NON_LINGUISTIC = [
  /<\/?[a-zA-Z][^<>]*>/g, // markup tags
  /&(?:[a-zA-Z]+|#\d+|#x[\da-fA-F]+);/g, // HTML entities
  /\b(?:https?|mailto|tel):[^\s"'<>]+/g, // URLs
  /[\w.+-]+@[\w-]+(?:\.[\w-]+)+/g, // email addresses
];
const EXCERPT_LENGTH = 60;

/** UI source holds presentation everywhere; the server only at its email and
 * response boundaries (its other strings are API docs and diagnostics). */
type Surface = 'ui' | 'server';
const SURFACES: ReadonlyArray<readonly [RegExp, Surface]> = [
  [/^apps\/(?:web|desktop)\/src\//, 'ui'],
  [/^apps\/server\/src\//, 'server'],
];
const SKIPPED_PATH_PATTERN =
  /\/tests\/|\/paraglide\/|\.gen\.[cm]?[jt]sx?$|\.d\.[cm]?ts$/;
const GENERATED_HEADER_PATTERN =
  /^\s*\/\*[\s\S]*?(?:Generated by|Do not edit manually)[\s\S]*?\*\//;
const SUPPRESSION_PATTERN =
  /^\s*(?:\/\/|\{?\/\*)\s*presentation-text-ignore\b(?::([^*]*))?(?:\*\/\}?)?\s*$/;
const SUPPRESSION_FORM =
  '// presentation-text-ignore: <why this text is not translatable copy>';
// EmailContent fields (email-layout.ts) a server email fills with copy.
const EMAIL_FIELDS = new Set([
  'subject',
  'greeting',
  'heading',
  'facts',
  'footer',
]);
// Attribute, property, variable and parameter names that carry copy: the
// ARIA text attributes, alt, and label/title/message-like names or suffixes.
const COPY_WORDS = [
  'label',
  'title',
  'message',
  'description',
  'placeholder',
  'heading',
  'subheading',
  'subtitle',
  'caption',
  'tooltip',
  'hint',
  'copy',
];
// A bare `text` is too often a CSS or data key; `emptyText` is still copy.
const COPY_SUFFIXES = [...COPY_WORDS, 'text'];
const capitalized = (word: string) => word[0]?.toUpperCase() + word.slice(1);
const ARIA_TEXT_ATTRIBUTE =
  'aria-(?:label|description|roledescription|valuetext|placeholder|braillelabel|brailleroledescription)';
// Names that carry copy: ARIA text attributes, alt, a copy word on its own,
// as a camelCase suffix (submitLabel) or a SCREAMING_CASE suffix (STATUS_LABELS).
const PRESENTATION_NAME = new RegExp(
  `^(?:${ARIA_TEXT_ATTRIBUTE}|alt|(?:${COPY_WORDS.join('|')})s?|[a-z][a-zA-Z\\d]*(?:${COPY_SUFFIXES.map(capitalized).join('|')})s?|(?:[A-Z\\d]+_)+(?:${COPY_SUFFIXES.join('|').toUpperCase()})S?)$`,
);

interface Finding {
  node: ts.Node;
  context: string;
  text: string;
}

interface Failure {
  line: number;
  column: number;
  message: string;
}

function surfaceOf({ path, source }: SourceFile): Surface | undefined {
  if (
    SKIPPED_PATH_PATTERN.test(path) ||
    GENERATED_HEADER_PATTERN.test(source)
  ) {
    return undefined;
  }
  return SURFACES.find(([pattern]) => pattern.test(path))?.[1];
}

/** True when text still holds a letter once markup, URLs and addresses go. */
function isCopy(text: string): boolean {
  const stripped = NON_LINGUISTIC.reduce(
    (value, pattern) => value.replace(pattern, ' '),
    text,
  );
  return LETTER.test(stripped);
}

function excerpt(text: string): string {
  const flat = text.replace(/\s+/g, ' ').trim();
  return flat.length > EXCERPT_LENGTH
    ? `${flat.slice(0, EXCERPT_LENGTH)}…`
    : flat;
}

function scriptKindFor(path: string): ts.ScriptKind {
  return /\.[cm]?[jt]sx$/.test(path) ? ts.ScriptKind.TSX : ts.ScriptKind.TS;
}

/** The literal text an expression can evaluate to, through branches and
 * fallbacks; calls, identifiers and property reads are runtime values. */
function textTerminals(expression: ts.Expression): ts.Node[] {
  if (
    ts.isParenthesizedExpression(expression) ||
    ts.isAsExpression(expression) ||
    ts.isSatisfiesExpression(expression) ||
    ts.isNonNullExpression(expression)
  ) {
    return textTerminals(expression.expression);
  }
  if (ts.isConditionalExpression(expression)) {
    return [
      ...textTerminals(expression.whenTrue),
      ...textTerminals(expression.whenFalse),
    ];
  }
  if (ts.isBinaryExpression(expression)) {
    const { kind } = expression.operatorToken;
    const { left, right } = expression;
    if (kind === ts.SyntaxKind.AmpersandAmpersandToken) {
      return textTerminals(right);
    }
    if (
      kind === ts.SyntaxKind.BarBarToken ||
      kind === ts.SyntaxKind.QuestionQuestionToken ||
      kind === ts.SyntaxKind.PlusToken
    ) {
      return [...textTerminals(left), ...textTerminals(right)];
    }
    return [];
  }
  return ts.isStringLiteralLike(expression) ||
    ts.isTemplateExpression(expression)
    ? [expression]
    : [];
}

function unwrap(expression: ts.Expression): ts.Expression {
  return ts.isParenthesizedExpression(expression) ||
    ts.isAsExpression(expression) ||
    ts.isSatisfiesExpression(expression)
    ? unwrap(expression.expression)
    : expression;
}

/** Text terminals of a map or list's values (never its keys). */
function valueTerminals(expression: ts.Expression): ts.Node[] {
  const value = unwrap(expression);
  if (ts.isObjectLiteralExpression(value)) {
    return value.properties.flatMap((property) =>
      ts.isPropertyAssignment(property)
        ? valueTerminals(property.initializer)
        : [],
    );
  }
  if (ts.isArrayLiteralExpression(value)) {
    return value.elements.flatMap(valueTerminals);
  }
  return textTerminals(value);
}

// Calls whose first argument is shown to the person as is.
const PRESENTATION_CALL =
  /^(?:toast(?:\.(?:success|error|info|warning|message|loading))?|(?:window\.)?(?:alert|confirm|prompt))$/;
// Zod checks whose string arguments become form validation messages.
const ZOD_MESSAGE_METHODS = new Set([
  'string',
  'number',
  'boolean',
  'date',
  'email',
  'url',
  'uuid',
  'min',
  'max',
  'length',
  'nonempty',
  'regex',
  'startsWith',
  'endsWith',
  'includes',
  'positive',
  'negative',
  'nonnegative',
  'nonpositive',
  'int',
  'gt',
  'gte',
  'lt',
  'lte',
  'multipleOf',
  'refine',
]);
// These take the matched text first and the message second.
const ZOD_PATTERN_METHODS = new Set(['startsWith', 'endsWith', 'includes']);

const DIAGNOSTIC_RECEIVERS = new Set(['console', 'logger', 'log']);

function rootName(expression: ts.Expression): string | undefined {
  if (ts.isIdentifier(expression)) return expression.text;
  if (
    ts.isPropertyAccessExpression(expression) ||
    ts.isCallExpression(expression)
  ) {
    return rootName(expression.expression);
  }
  return undefined;
}

/** Thrown errors and log calls carry English diagnostics, not copy. */
function isDiagnostic(node: ts.Node): boolean {
  for (let current = node.parent; current; current = current.parent) {
    if (ts.isThrowStatement(current)) return true;
    if (
      ts.isNewExpression(current) &&
      /Error$/.test(current.expression.getText())
    ) {
      return true;
    }
    if (ts.isCallExpression(current)) {
      const callee = current.expression;
      const receiver = ts.isPropertyAccessExpression(callee)
        ? callee.expression
        : undefined;
      const name =
        receiver && ts.isPropertyAccessExpression(receiver)
          ? receiver.name.text
          : receiver && rootName(receiver);
      if (name && DIAGNOSTIC_RECEIVERS.has(name)) return true;
    }
  }
  return false;
}

function propertyName(
  name: ts.PropertyName | ts.BindingName,
): string | undefined {
  return ts.isIdentifier(name) ||
    ts.isStringLiteral(name) ||
    ts.isPrivateIdentifier(name)
    ? name.text
    : undefined;
}

function literalText(node: ts.Node): string {
  if (ts.isStringLiteralLike(node)) return node.text;
  if (ts.isTemplateExpression(node)) return node.getText().slice(1, -1);
  return node.getText();
}

// Interpolations are runtime values, so only the authored parts count.
function authoredText(node: ts.Node): string {
  return ts.isTemplateExpression(node)
    ? [
        node.head.text,
        ...node.templateSpans.map(({ literal }) => literal.text),
      ].join(' ')
    : literalText(node);
}

/** The property name an object literal sits under, as in `action: { … }`. */
function ownerProperty(object: ts.Node): string | undefined {
  const { parent } = object;
  return ts.isPropertyAssignment(parent)
    ? propertyName(parent.name)
    : undefined;
}

/** True for an object literal passed, directly or nested, to `.send(…)`. */
function isSentResponse(object: ts.ObjectLiteralExpression): boolean {
  let argument: ts.Node = object;
  while (
    ts.isPropertyAssignment(argument.parent) &&
    ts.isObjectLiteralExpression(argument.parent.parent)
  ) {
    argument = argument.parent.parent;
  }
  const call = argument.parent;
  return (
    ts.isCallExpression(call) &&
    ts.isPropertyAccessExpression(call.expression) &&
    call.expression.name.text === 'send' &&
    call.arguments.includes(argument as ts.Expression)
  );
}

function serverFindingsIn(sourceFile: ts.SourceFile): Finding[] {
  const findings: Finding[] = [];
  const report = ({
    expression,
    context,
  }: {
    expression: ts.Expression;
    context: string;
  }) => {
    for (const node of valueTerminals(expression)) {
      if (isCopy(authoredText(node))) {
        findings.push({ node, context, text: literalText(node) });
      }
    }
  };
  const visit = (node: ts.Node) => {
    const name = ts.isPropertyAssignment(node)
      ? propertyName(node.name)
      : undefined;
    if (name && ts.isPropertyAssignment(node)) {
      const { initializer, parent } = node;
      if (EMAIL_FIELDS.has(name)) {
        report({ expression: initializer, context: `email "${name}"` });
      } else if (name === 'label' && ownerProperty(parent) === 'action') {
        report({ expression: initializer, context: 'email "action.label"' });
      } else if (name === 'message' && isSentResponse(parent)) {
        report({ expression: initializer, context: 'response "message"' });
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(sourceFile);
  return findings;
}

type FunctionWithBody =
  | ts.FunctionDeclaration
  | ts.FunctionExpression
  | ts.ArrowFunction
  | ts.MethodDeclaration;

function isFunctionWithBody(node: ts.Node): node is FunctionWithBody {
  return (
    (ts.isFunctionDeclaration(node) ||
      ts.isFunctionExpression(node) ||
      ts.isArrowFunction(node) ||
      ts.isMethodDeclaration(node)) &&
    node.body !== undefined
  );
}

/** A function's own name, or the variable or property it is assigned to. */
function functionName(node: FunctionWithBody): string | undefined {
  if (node.name) return propertyName(node.name);
  const { parent } = node;
  return ts.isVariableDeclaration(parent) || ts.isPropertyAssignment(parent)
    ? propertyName(parent.name)
    : undefined;
}

/** A declared literal return type (`'hourly' | 'daily'`) says it returns keys. */
function returnsKeys(node: FunctionWithBody): boolean {
  const { type } = node;
  if (!type) return false;
  const members = ts.isUnionTypeNode(type) ? type.types : [type];
  return members.every(ts.isLiteralTypeNode);
}

/** The values a function returns, skipping nested functions' returns. */
function returnedExpressions(node: FunctionWithBody): ts.Expression[] {
  const { body } = node;
  if (!body) return [];
  if (!ts.isBlock(body)) return [body];
  const returned: ts.Expression[] = [];
  const visit = (child: ts.Node) => {
    if (isFunctionWithBody(child)) return;
    if (ts.isReturnStatement(child) && child.expression) {
      returned.push(child.expression);
    }
    ts.forEachChild(child, visit);
  };
  ts.forEachChild(body, visit);
  return returned;
}

function uiFindingsIn(sourceFile: ts.SourceFile): Finding[] {
  const findings: Finding[] = [];
  const reported = new Set<ts.Node>();
  const report = ({
    expression,
    context,
    terminals = textTerminals,
  }: {
    expression: ts.Expression;
    context: string;
    terminals?: (expression: ts.Expression) => ts.Node[];
  }) => {
    for (const node of terminals(expression)) {
      if (reported.has(node) || !isCopy(authoredText(node))) continue;
      reported.add(node);
      findings.push({ node, context, text: literalText(node) });
    }
  };
  const reportNamed = ({
    name,
    initializer,
  }: {
    name: ts.PropertyName | ts.BindingName;
    initializer: ts.Expression | undefined;
  }) => {
    const text = propertyName(name);
    if (!initializer || !text || !PRESENTATION_NAME.test(text)) return;
    if (isDiagnostic(initializer)) return;
    const { parent } = name;
    if (ts.isPropertyAssignment(parent)) {
      report({ expression: initializer, context: `property "${text}"` });
    } else if (ts.isVariableDeclaration(parent)) {
      const value = unwrap(initializer);
      const isMap =
        ts.isObjectLiteralExpression(value) ||
        ts.isArrayLiteralExpression(value);
      report({
        expression: initializer,
        context: isMap ? `value of "${text}"` : `variable "${text}"`,
        terminals: valueTerminals,
      });
    } else {
      report({ expression: initializer, context: `default "${text}"` });
    }
  };
  const reportCall = (call: ts.CallExpression) => {
    const callee = call.expression.getText();
    const [first] = call.arguments;
    if (PRESENTATION_CALL.test(callee) && first) {
      report({ expression: first, context: `argument of "${callee}"` });
    }
    if (
      !ts.isPropertyAccessExpression(call.expression) ||
      rootName(call.expression) !== 'z'
    ) {
      return;
    }
    const method = call.expression.name.text;
    if (!ZOD_MESSAGE_METHODS.has(method)) return;
    const messages = ZOD_PATTERN_METHODS.has(method)
      ? call.arguments.slice(1)
      : call.arguments;
    for (const expression of messages) {
      report({ expression, context: `validation message of "${method}"` });
    }
  };
  const visit = (node: ts.Node) => {
    if (ts.isJsxText(node) && isCopy(node.text)) {
      findings.push({ node, context: 'JSX text', text: node.text });
    }
    if (
      ts.isJsxExpression(node) &&
      node.expression &&
      (ts.isJsxElement(node.parent) || ts.isJsxFragment(node.parent))
    ) {
      report({ expression: node.expression, context: 'JSX expression' });
    }
    if (ts.isJsxAttribute(node) && node.initializer) {
      const name = node.name.getText();
      const { initializer } = node;
      const expression = ts.isJsxExpression(initializer)
        ? initializer.expression
        : initializer;
      if (expression && PRESENTATION_NAME.test(name)) {
        report({ expression, context: `attribute "${name}"` });
      }
    }
    if (ts.isCallExpression(node)) reportCall(node);
    const returningName = isFunctionWithBody(node)
      ? functionName(node)
      : undefined;
    if (
      returningName &&
      isFunctionWithBody(node) &&
      PRESENTATION_NAME.test(returningName) &&
      !returnsKeys(node)
    ) {
      for (const expression of returnedExpressions(node)) {
        report({ expression, context: `return of "${returningName}"` });
      }
    }
    if (
      ts.isBinaryExpression(node) &&
      node.operatorToken.kind === ts.SyntaxKind.EqualsToken &&
      node.left.getText() === 'document.title'
    ) {
      report({
        expression: node.right,
        context: 'assignment to "document.title"',
      });
    }
    if (
      ts.isPropertyAssignment(node) ||
      ts.isVariableDeclaration(node) ||
      ts.isBindingElement(node) ||
      ts.isParameter(node)
    ) {
      reportNamed({ name: node.name, initializer: node.initializer });
    }
    ts.forEachChild(node, visit);
  };
  visit(sourceFile);
  return findings;
}

function locationOf({
  sourceFile,
  node,
}: {
  sourceFile: ts.SourceFile;
  node: ts.Node;
}): ts.LineAndCharacter {
  // A JSX text's `text` starts at `pos` with its leading whitespace; offset
  // from there (getStart() already skips that whitespace).
  const start = ts.isJsxText(node)
    ? node.pos + node.text.length - node.text.trimStart().length
    : node.getStart(sourceFile);
  return sourceFile.getLineAndCharacterOfPosition(start);
}

function failuresIn({
  file,
  surface,
}: {
  file: SourceFile;
  surface: Surface;
}): Failure[] {
  const sourceFile = ts.createSourceFile(
    file.path,
    file.source,
    ts.ScriptTarget.Latest,
    true,
    scriptKindFor(file.path),
  );
  const findings =
    surface === 'ui' ? uiFindingsIn(sourceFile) : serverFindingsIn(sourceFile);
  const failures: Failure[] = [];
  const suppressions = new Map<number, boolean>();
  sourceFile.text.split('\n').forEach((text, index) => {
    const suppression = text.match(SUPPRESSION_PATTERN);
    if (!suppression) return;
    const line = index + 1;
    suppressions.set(line + 1, false);
    if (!suppression[1]?.trim()) {
      failures.push({
        line,
        column: 1,
        message: `presentation-text-ignore needs a reason: ${SUPPRESSION_FORM}`,
      });
    }
  });
  for (const { node, context, text } of findings) {
    const { line, character } = locationOf({ sourceFile, node });
    if (suppressions.has(line + 1)) {
      suppressions.set(line + 1, true);
      continue;
    }
    failures.push({
      line: line + 1,
      column: character + 1,
      message: `${context} "${excerpt(text)}": ${FIX}`,
    });
  }
  for (const [line, used] of suppressions) {
    if (!used) {
      failures.push({
        line: line - 1,
        column: 1,
        message:
          'presentation-text-ignore suppresses nothing on the next line: remove it',
      });
    }
  }
  return failures.sort((a, b) => a.line - b.line || a.column - b.column);
}

export function getPresentationTextFailures({
  files,
}: {
  files: SourceFile[];
}): string[] {
  return files.flatMap((file) => {
    const surface = surfaceOf(file);
    if (!surface) return [];
    return failuresIn({ file, surface }).map(
      ({ line, column, message }) =>
        `${file.path}:${line}:${column}: ${message}`,
    );
  });
}

// `bun tooling/validation/presentation-text-guard.ts [path…]`: the given
// repo-relative files (read from the working directory), or the whole tree.
if (import.meta.main) {
  const paths = process.argv.slice(2);
  const files =
    paths.length > 0
      ? paths.map((path) => ({ path, source: readFileSync(path, 'utf8') }))
      : readApplicationSourceFiles();
  const failures = getPresentationTextFailures({ files });
  if (failures.length > 0) {
    console.error(failures.join('\n'));
    process.exitCode = 1;
  }
}
