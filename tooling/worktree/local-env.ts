/**
 * `bun run env:local [--revalidate]`: generates the worktree's one ignored
 * root `.env.local` (ADR-0005) — its identity, service ports, the URL set
 * derived from them on its private hostname under this machine's
 * `CHURCH_DEV_DOMAIN` (or `localhost`), and a unique Better Auth secret.
 * Reruns reproduce the file. `--revalidate` (for launch) keeps it while
 * every persisted port is still free, and otherwise reallocates the whole
 * port set and rewrites every dependent URL in one atomic replace.
 *
 * Below the generated values it writes the local-only defaults a fresh
 * worktree needs to serve and test, then the machine-shared values (where
 * Unleash runs and its token, this machine's development domain) from one
 * ignored `church-shared.env` in the shared Git directory. A shared value
 * may replace a default, never a generated value.
 *
 * Allocation runs under one kernel `flock` in the repository's shared Git
 * directory, so worktrees generating concurrently see each other's claims.
 */

const LOCAL_ENV_FILE = '.env.local';
const LEGACY_ENV_FILE = '.env';
// Value files beside the service schemas Varlock runs from (`--path`); unlike
// the root `.env`, they take precedence over the root `.env.local`.
const PACKAGE_VALUE_FILES = [
  'apps/server/.env',
  'apps/server/.env.local',
  'apps/web/.env',
  'apps/web/.env.local',
  'packages/db/.env',
  'packages/db/.env.local',
  'packages/auth/.env',
  'packages/auth/.env.local',
];
const GENERATED_HEADER =
  '# Generated by `bun run env:local` (tooling/worktree/local-env.ts). Do not edit; rerun it.';
const LOCK_FILE = 'church-local-env.lock';
const LOCAL_DEFAULTS = new Map([['ENABLE_DEBUG_ENDPOINTS', 'true']]);
const OVERRIDABLE_VALUES_HEADER = `# Local defaults, then values from the shared Git directory's ${SHARED_VALUES_FILE}.`;
const LOCK_HELD_VARIABLE = 'CHURCH_LOCAL_ENV_LOCK_HELD';
const REVALIDATE_FLAG = '--revalidate';
const AUTH_SECRET_BYTES = 32;

const PORT_VARIABLES: Record<PortService, string> = {
  server: 'CHURCH_SERVER_PORT',
  web: 'CHURCH_WEB_PORT',
  e2eServer: 'PW_SERVER_PORT',
  e2eWeb: 'PW_WEB_PORT',
};

interface LocalEnv {
  worktree: string;
  ports: PortSet;
  betterAuthSecret: string;
  devDomain: string | undefined;
}

interface RenderLocalEnvInput {
  generated: Map<string, string>;
  shared: SharedValues;
}

export interface WorktreeContext {
  root: string;
  commonDir: string;
  repository: string;
  isPrimary: boolean;
  name: string;
}

interface GitInput {
  cwd: string;
  args: string[];
}

function git(input: GitInput): string {
  return execFileSync('git', input.args, {
    cwd: input.cwd,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  }).trim();
}

/** The checked-out branch, including an unborn one; undefined when detached. */
function currentBranch(input: CwdInput): string | undefined {
  try {
    return git({
      cwd: input.cwd,
      args: ['symbolic-ref', '--quiet', '--short', 'HEAD'],
    });
  } catch {
    return undefined;
  }
}

export interface CwdInput {
  cwd: string;
}

export function worktreeContext(input: CwdInput): WorktreeContext {
  const [root = '', gitDir, commonDir = ''] = git({
    cwd: input.cwd,
    args: [
      'rev-parse',
      '--path-format=absolute',
      '--show-toplevel',
      '--git-dir',
      '--git-common-dir',
    ],
  }).split('\n');

  return {
    root,
    commonDir,
    repository: basename(dirname(commonDir)),
    isPrimary: gitDir === commonDir,
    // A detached HEAD has no branch; the directory name is stable instead.
    name: currentBranch(input) ?? basename(root),
  };
}

interface ValuesInput {
  values: Map<string, string>;
}

function portsFrom(input: ValuesInput): PortSet | undefined {
  const ports = {} as PortSet;

  for (const service of PORT_SERVICES) {
    const port = Number(input.values.get(PORT_VARIABLES[service]));
    if (!Number.isInteger(port) || port <= 0) return undefined;
    ports[service] = port;
  }

  return ports;
}

interface ContentInput {
  content: string;
}

function hasGeneratedHeader(input: ContentInput): boolean {
  return input.content.startsWith(`${GENERATED_HEADER}\n`);
}

interface LocalEnvInput {
  localEnv: LocalEnv;
}

interface WorktreeInput {
  worktree: string;
}

/**
 * One `DATABASE_URL` whose value Varlock selects from `CHURCH_EXEC_PURPOSE`,
 * so every purpose-wrapped command gets this worktree's matching database
 * from the single `.env.local`. Any other purpose (`unit`) resolves no
 * database rather than falling through to the purpose name.
 */
function databaseUrlSelector(input: WorktreeInput): string {
  const urls = worktreeDatabaseUrls({ worktree: input.worktree });
  const cases = WORKTREE_DATABASE_PURPOSES.map(
    (purpose) => `${purpose}, "${urls[purpose]}"`,
  );

  return `remap($CHURCH_EXEC_PURPOSE, ${cases.join(', ')}, regex(.*), undefined)`;
}

function generatedValues(input: LocalEnvInput): Map<string, string> {
  const { worktree, ports, betterAuthSecret, devDomain } = input.localEnv;
  // Manual development only: E2E derives its own loopback URL set from the
  // PW_* ports (tooling/env/e2e-environment.ts).
  const host = worktreeHostname({ worktree, domain: devDomain });
  const serverUrl = `http://${host}:${ports.server}`;
  const webUrl = `http://${host}:${ports.web}`;

  return new Map([
    ['CHURCH_WORKTREE', worktree],
    ...PORT_SERVICES.map((service): [string, string] => [
      PORT_VARIABLES[service],
      String(ports[service]),
    ]),
    ['BETTER_AUTH_URL', serverUrl],
    ['VITE_SERVER_URL', serverUrl],
    ['CORS_ORIGIN', webUrl],
    ['BETTER_AUTH_SECRET', betterAuthSecret],
    ['DATABASE_URL', databaseUrlSelector({ worktree })],
  ]);
}

interface ValueMapInput {
  values: Map<string, string>;
}

function valueLines(input: ValueMapInput): string[] {
  return [...input.values].map(([key, value]) => `${key}=${value}`);
}

function renderLocalEnv(input: RenderLocalEnvInput): string {
  const overridableValues = new Map([
    ...LOCAL_DEFAULTS,
    ...input.shared.values,
  ]);

  return [
    GENERATED_HEADER,
    ...valueLines({ values: input.generated }),
    OVERRIDABLE_VALUES_HEADER,
    ...valueLines({ values: overridableValues }),
    '',
  ].join('\n');
}

interface RefuseGeneratedKeysInput {
  shared: SharedValues;
  generatedKeys: ReadonlySet<string>;
}

/** Refuses a shared value for any key env:local itself generates. */
function refuseGeneratedKeys(input: RefuseGeneratedKeysInput): void {
  const refused = [...input.shared.values.keys()].filter((key) =>
    input.generatedKeys.has(key),
  );

  if (refused.length > 0) {
    throw new Error(
      `${input.shared.path} sets ${refused.join(', ')}, which env:local generates per worktree. Remove ${refused.length === 1 ? 'it' : 'them'} from that file, then rerun.`,
    );
  }
}

interface ContextInput {
  context: WorktreeContext;
}

interface OtherWorktreeClaims {
  identities: Set<string>;
  ports: Set<number>;
}

/** Identities and ports persisted in every other active worktree's
 * generated `.env.local`. */
function claimsOfOtherWorktrees(input: ContextInput): OtherWorktreeClaims {
  const roots = git({
    cwd: input.context.root,
    args: ['worktree', 'list', '--porcelain'],
  })
    .split('\n')
    .filter((line) => line.startsWith('worktree '))
    .map((line) => line.slice('worktree '.length))
    .filter((root) => root !== input.context.root);

  const claims: OtherWorktreeClaims = {
    identities: new Set(),
    ports: new Set(),
  };

  for (const root of roots) {
    const content = readContent({ path: join(root, LOCAL_ENV_FILE) });
    if (!content || !hasGeneratedHeader({ content })) continue;

    const values = parseValues({ content });
    const identity = values.get('CHURCH_WORKTREE');
    if (identity) claims.identities.add(identity);
    for (const port of Object.values(portsFrom({ values }) ?? {})) {
      claims.ports.add(port);
    }
  }

  return claims;
}

export interface ActiveWorktreeIdentitiesInput {
  cwd: string;
  /** Leave out the worktree containing `cwd`. */
  excludeCurrent?: boolean;
}

/**
 * Every identity an active worktree of this repository holds or would
 * derive: the one persisted in its generated `.env.local`, plus the one its
 * branch (or directory, when detached) derives, which protects a worktree
 * still bootstrapping. The primary checkout's is always included. A worktree
 * whose directory is gone (Git marks it prunable) is no longer active.
 */
export function activeWorktreeIdentities(
  input: ActiveWorktreeIdentitiesInput,
): Set<string> {
  const excludedRoot = input.excludeCurrent
    ? worktreeContext({ cwd: input.cwd }).root
    : undefined;
  // Porcelain lists the primary checkout first, one blank-line-separated
  // record per worktree.
  const records = git({
    cwd: input.cwd,
    args: ['worktree', 'list', '--porcelain'],
  })
    .split('\n\n')
    .map((record) => record.split('\n'));

  const identities = new Set([PRIMARY_WORKTREE_IDENTITY]);

  for (const [index, lines] of records.entries()) {
    const root = lines
      .find((line) => line.startsWith('worktree '))
      ?.slice('worktree '.length);
    const isGone = lines.some((line) => line.startsWith('prunable'));
    if (!root || isGone || root === excludedRoot) continue;

    const branch = lines
      .find((line) => line.startsWith('branch refs/heads/'))
      ?.slice('branch refs/heads/'.length);
    identities.add(
      deriveWorktreeIdentity({
        name: branch ?? basename(root),
        isPrimary: index === 0,
      }),
    );

    const content = readContent({ path: join(root, LOCAL_ENV_FILE) });
    if (!content || !hasGeneratedHeader({ content })) continue;

    const identity = parseValues({ content }).get('CHURCH_WORKTREE');
    if (identity) identities.add(identity);
  }

  return identities;
}

interface ListenerCheckInput {
  hostname: string;
  port: number;
}

function canListen(input: ListenerCheckInput): boolean {
  try {
    Bun.listen({ ...input, socket: { data() {} } }).stop(true);
    return true;
  } catch (error) {
    // A host without IPv6 cannot bind `::` at all; only a conflict counts.
    return (
      input.hostname === '::' &&
      (error as { code?: string }).code !== 'EADDRINUSE'
    );
  }
}

/** Free for both an IPv4 and an IPv6 listener (Vite may bind `::1`). */
function isHostPortFree(input: PortAvailabilityInput): boolean {
  return (
    canListen({ hostname: '0.0.0.0', port: input.port }) &&
    canListen({ hostname: '::', port: input.port })
  );
}

interface LegacyOverridesInput {
  root: string;
  generated: Map<string, string>;
}

/**
 * Keys whose value in the legacy root `.env` differs from the generated one.
 * Varlock and Vite prefer `.env.local`, while not-yet-migrated scripts still
 * read `.env` alone, so such keys now diverge between commands.
 */
function legacyOverrides(input: LegacyOverridesInput): string[] {
  const legacy = parseValues({
    content: readContent({ path: join(input.root, LEGACY_ENV_FILE) }) ?? '',
  });

  return [...input.generated.keys()].filter((key) => {
    const legacyValue = unquoted({ value: legacy.get(key) });
    return (
      legacyValue !== undefined &&
      legacyValue !== unquoted({ value: input.generated.get(key) })
    );
  });
}

interface PackageShadow {
  file: string;
  keys: string[];
}

/**
 * Generated keys a package-local value file also sets. Varlock prefers the
 * package file for commands run through that package, so the generated value
 * (e.g. the purpose-selected DATABASE_URL) never reaches them.
 */
function packageShadows(input: LegacyOverridesInput): PackageShadow[] {
  return PACKAGE_VALUE_FILES.map((file) => {
    const values = parseValues({
      content: readContent({ path: join(input.root, file) }) ?? '',
    });
    return {
      file,
      keys: [...input.generated.keys()].filter((key) => values.has(key)),
    };
  }).filter((shadow) => shadow.keys.length > 0);
}

interface WriteAtomicallyInput {
  path: string;
  content: string;
}

function writeAtomically(input: WriteAtomicallyInput): void {
  // Named to match `.env*.local` in .gitignore: it holds the secret too.
  const temporary = join(dirname(input.path), `.env.${process.pid}.tmp.local`);
  writeFileSync(temporary, input.content, { mode: 0o600 });
  renameSync(temporary, input.path);
}

/** The identity in this worktree's generated `.env.local`; undefined when
 * the file is absent or was not generated by env:local. */
export function readGeneratedWorktreeIdentity(
  input: CwdInput,
): string | undefined {
  const context = worktreeContext(input);
  const content = readContent({ path: join(context.root, LOCAL_ENV_FILE) });
  if (content === undefined || !hasGeneratedHeader({ content })) {
    return undefined;
  }

  const identity = parseValues({ content }).get('CHURCH_WORKTREE');
  if (
    identity !== undefined &&
    (identity === PRIMARY_WORKTREE_IDENTITY) !== context.isPrimary
  ) {
    throw new Error(
      `${LOCAL_ENV_FILE} names worktree "${identity}", which ${context.isPrimary ? 'only a linked worktree may hold' : 'is reserved for the primary checkout'}. Delete it and rerun \`bun run env:local\`.`,
    );
  }

  return identity;
}

/** The ports persisted in this worktree's generated `.env.local`;
 * undefined when the file is absent, not generated, or incomplete. */
export function readGeneratedPorts(input: CwdInput): PortSet | undefined {
  const context = worktreeContext(input);
  const content = readContent({ path: join(context.root, LOCAL_ENV_FILE) });
  if (content === undefined || !hasGeneratedHeader({ content })) {
    return undefined;
  }

  return portsFrom({ values: parseValues({ content }) });
}

/** Every value file this worktree's commands may read: its root and
 * package-local files and the shared Git directory's machine-shared values. */
export function valueFilePaths(input: CwdInput): string[] {
  const context = worktreeContext(input);

  return [
    ...[LOCAL_ENV_FILE, LEGACY_ENV_FILE, ...PACKAGE_VALUE_FILES].map((file) =>
      join(context.root, file),
    ),
    sharedValuesPath({ commonDir: context.commonDir }),
  ];
}

interface GenerateInput {
  cwd: string;
  revalidate: boolean;
}

function generateLocalEnv(input: GenerateInput): void {
  const context = worktreeContext({ cwd: input.cwd });
  const path = join(context.root, LOCAL_ENV_FILE);
  const existingContent = readContent({ path });

  if (
    existingContent !== undefined &&
    !hasGeneratedHeader({ content: existingContent })
  ) {
    throw new Error(
      `${path} was not generated by env:local. Move its values elsewhere or delete it, then rerun.`,
    );
  }

  const existing = parseValues({ content: existingContent ?? '' });
  const worktree =
    existing.get('CHURCH_WORKTREE') ??
    deriveWorktreeIdentity({
      name: context.name,
      isPrimary: context.isPrimary,
    });
  const claims = claimsOfOtherWorktrees({ context });

  if (claims.identities.has(worktree)) {
    throw new Error(
      `Worktree identity "${worktree}" is already held by another active worktree; its databases would be shared. Rename this worktree's branch or directory, then rerun.`,
    );
  }

  const isAvailable = (availability: PortAvailabilityInput): boolean =>
    !claims.ports.has(availability.port) && isHostPortFree(availability);

  const persistedPorts = portsFrom({ values: existing });
  const unavailablePorts = Object.values(persistedPorts ?? {}).filter(
    (port) => input.revalidate && !isAvailable({ port }),
  );

  if (worktree === PRIMARY_WORKTREE_IDENTITY && unavailablePorts.length > 0) {
    throw new Error(
      `The primary worktree keeps its established ports, but ${unavailablePorts.join(', ')} ${unavailablePorts.length === 1 ? 'is' : 'are'} in use. Stop whatever holds ${unavailablePorts.length === 1 ? 'it' : 'them'}, then rerun.`,
    );
  }

  const keepPersisted =
    persistedPorts !== undefined && unavailablePorts.length === 0;
  const ports = keepPersisted
    ? persistedPorts
    : allocatePorts({
        repository: context.repository,
        worktree,
        isAvailable,
      });

  const shared = readSharedValues({ commonDir: context.commonDir });
  const worktreeValues = generatedValues({
    localEnv: {
      worktree,
      ports,
      betterAuthSecret:
        existing.get('BETTER_AUTH_SECRET') ??
        randomBytes(AUTH_SECRET_BYTES).toString('hex'),
      devDomain: sharedDevDomain({ shared }),
    },
  });
  refuseGeneratedKeys({
    shared,
    generatedKeys: new Set(worktreeValues.keys()),
  });
  const content = renderLocalEnv({ generated: worktreeValues, shared });

  const unchanged = content === existingContent;

  if (!unchanged) {
    writeAtomically({ path, content });
  }

  const summary = PORT_SERVICES.map(
    (service) => `${service}=${ports[service]}`,
  ).join(' ');
  console.log(
    `env:local ${unchanged ? 'unchanged' : 'written'}: worktree=${worktree} ${summary}`,
  );

  const generated = parseValues({ content });
  const overridden = legacyOverrides({ root: context.root, generated });

  if (overridden.length > 0) {
    console.warn(
      `⚠ env:local overrides values from the legacy ${LEGACY_ENV_FILE} for: ${overridden.join(', ')}. Varlock-wrapped commands and Vite now use the generated values; scripts still reading ${LEGACY_ENV_FILE} directly do not.`,
    );
  }

  if (!existsSync(shared.path)) {
    console.warn(
      `⚠ ${shared.path} does not exist, so machine-shared values such as UNLEASH_API_URL and UNLEASH_API_TOKEN are missing and server commands will fail validation. Create it (docs/agents/tooling.md, "Worktree bootstrap"), then rerun.`,
    );
  }

  for (const shadow of packageShadows({ root: context.root, generated })) {
    console.warn(
      `⚠ ${shadow.file} sets ${shadow.keys.join(', ')}, which take${shadow.keys.length === 1 ? 's' : ''} precedence over the generated values for commands run through that package. Remove ${shadow.keys.length === 1 ? 'it' : 'them'} from ${shadow.file}.`,
    );
  }
}

interface ArgvInput {
  argv: string[];
}

/** Re-executes this script under the shared allocation lock. */
function runUnderLock(input: ArgvInput): number {
  const context = worktreeContext({ cwd: process.cwd() });
  const result = spawnSync(
    'flock',
    [
      join(context.commonDir, LOCK_FILE),
      process.execPath,
      import.meta.path,
      ...input.argv,
    ],
    {
      stdio: 'inherit',
      env: { ...process.env, [LOCK_HELD_VARIABLE]: '1' },
    },
  );

  if (result.error) {
    console.error(
      `✖ env:local could not take the allocation lock with flock: ${result.error.message}`,
    );
  }

  return result.status ?? 1;
}

function main(): void {
  const argv = process.argv.slice(2);

  try {
    if (process.env[LOCK_HELD_VARIABLE] !== '1') {
      process.exit(runUnderLock({ argv }));
    }

    generateLocalEnv({
      cwd: process.cwd(),
      revalidate: argv.includes(REVALIDATE_FLAG),
    });
  } catch (error) {
    console.error(
      `✖ env:local failed: ${error instanceof Error ? error.message : String(error)}`,
    );
    process.exit(1);
  }
}

if (import.meta.main) {
  main();
}
